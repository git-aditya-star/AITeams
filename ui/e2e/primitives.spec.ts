import { expect, test } from './fixtures'

const feature = async (qa: { api: (p: string) => Promise<any> }, key: string) =>
  ((await qa.api('/features?history=1')) as any[]).find((f) => f.key === key)

test('project picker: mouse, keyboard, Escape', async ({ page, qa }) => {
  await qa.open('/p/demo')
  const picker = page.getByRole('combobox', { name: 'Project' })
  await picker.click()
  await expect(page.getByRole('option', { name: 'demo' })).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(page.getByRole('listbox')).toBeHidden()
  await picker.focus()
  await page.keyboard.press('Enter')
  await expect(page.getByRole('option', { name: 'demo' })).toBeFocused()
  await page.keyboard.press('Enter')
  await expect(page.getByRole('listbox')).toBeHidden()
  await expect(picker).toHaveText('demo')
  await expect(page).toHaveURL(/\/p\/demo/)
})

test('feature phase and owner selects apply by mouse and keyboard', async ({ page, qa }) => {
  await qa.open('/p/demo?c=feature-1')
  const phase = page.getByRole('combobox', { name: 'Phase', exact: true })
  await expect(phase).toHaveText('build')
  await phase.click()
  await page.getByRole('option', { name: 'qa', exact: true }).click()
  await expect(phase).toHaveText('qa')
  await expect.poll(async () => (await feature(qa, 'F-1')).phase).toBe('qa')

  await phase.focus()
  await page.keyboard.press('ArrowDown') // opens on the current value
  await expect(page.getByRole('option', { name: 'qa', exact: true })).toBeFocused()
  await page.keyboard.press('ArrowUp')
  await expect(page.getByRole('option', { name: 'build', exact: true })).toBeFocused() // Radix moves focus on a timer
  await page.keyboard.press('Enter')
  await expect(phase).toHaveText('build')
  await expect.poll(async () => (await feature(qa, 'F-1')).phase).toBe('build')

  await phase.click()
  await page.keyboard.press('ArrowDown')
  await page.keyboard.press('Escape')
  await expect(page.getByRole('listbox')).toBeHidden()
  await expect(phase).toHaveText('build')

  const owner = page.getByRole('combobox', { name: 'Owner' })
  await expect(owner).toHaveText('Lead')
  await owner.click()
  await page.getByRole('option', { name: 'Frontend' }).click()
  await expect(owner).toHaveText('Frontend')
  await expect.poll(async () => (await feature(qa, 'F-1')).owner).toBe('frontend')
  await owner.click()
  await page.getByRole('option', { name: 'none' }).click()
  await expect(owner).toHaveText('none')
  await expect.poll(async () => (await feature(qa, 'F-1')).owner).toBeNull()
  await owner.focus()
  await page.keyboard.press('Enter')
  await expect(page.getByRole('option', { name: 'none' })).toBeFocused()
  await page.keyboard.press('ArrowDown')
  await expect(page.getByRole('option', { name: 'Manager' })).toBeFocused()
  await page.keyboard.press('Enter')
  await expect(owner).toHaveText('Manager')
  await expect.poll(async () => (await feature(qa, 'F-1')).owner).toBe('manager')
  await owner.click()
  await page.keyboard.press('Escape')
  await expect(page.getByRole('listbox')).toBeHidden()
  await expect(owner).toHaveText('Manager')
})

test('New task starter select picks who starts', async ({ page, qa }) => {
  await qa.open('/p/demo')
  const sidebar = page.locator('aside')
  await sidebar.getByRole('button', { name: 'New task' }).click()
  const starter = sidebar.getByRole('combobox', { name: 'Starter' })
  await expect(starter).toHaveText('Product')
  await starter.click()
  await page.keyboard.press('Escape')
  await expect(page.getByRole('listbox')).toBeHidden()
  await expect(starter).toHaveText('Product')
  await starter.focus()
  await page.keyboard.press('ArrowDown')
  await expect(page.getByRole('option', { name: 'Product' })).toBeFocused()
  await page.keyboard.press('ArrowDown')
  await expect(page.getByRole('option', { name: 'Lead' })).toBeFocused()
  await page.keyboard.press('Enter')
  await expect(starter).toHaveText('Lead')
  await starter.click()
  await page.getByRole('option', { name: 'Manager' }).click()
  await expect(starter).toHaveText('Manager')
  await starter.click()
  await page.getByRole('option', { name: 'Lead' }).click()
  await expect(starter).toHaveText('Lead')
  await sidebar.getByPlaceholder('What should the team do?').fill('Add a CSV import')
  await sidebar.getByRole('button', { name: 'Start' }).click()
  await expect(page.getByRole('heading', { name: 'Add a CSV import' })).toBeVisible()
  await expect(page.locator('main .mention', { hasText: '@lead' })).toBeVisible()
})

test('approval set-phase select and History reopen select', async ({ page, qa }) => {
  await qa.open('/p/demo?c=inbox')
  const card = page.locator('[data-card="approval-1"]')
  const setPhase = card.getByRole('combobox', { name: 'Set phase' })
  await expect(setPhase).toHaveText('unchanged')
  await setPhase.click()
  await page.keyboard.press('Escape')
  await expect(page.getByRole('listbox')).toBeHidden()
  await expect(setPhase).toHaveText('unchanged')
  await setPhase.focus()
  await page.keyboard.press('Enter')
  await expect(page.getByRole('option', { name: 'unchanged' })).toBeFocused()
  await page.keyboard.press('ArrowDown')
  await expect(page.getByRole('option', { name: 'intake' })).toBeFocused()
  await page.keyboard.press('ArrowDown')
  await expect(page.getByRole('option', { name: 'spec', exact: true })).toBeFocused()
  await page.keyboard.press('Enter')
  await expect(setPhase).toHaveText('spec')
  await card.getByRole('button', { name: 'Approve' }).click()
  await expect.poll(async () => (await feature(qa, 'F-1')).phase).toBe('spec')

  await page.locator('aside').getByRole('button', { name: /^History/ }).click()
  const reopen = page.getByRole('combobox', { name: 'Reopen F-2' })
  await expect(reopen).toHaveText('reopen…')
  await reopen.click()
  await page.keyboard.press('Escape')
  await expect(page.getByRole('listbox')).toBeHidden()
  await expect(reopen).toHaveText('reopen…')
  await reopen.focus()
  await page.keyboard.press('Enter')
  await page.keyboard.press('ArrowDown') // nothing is selected, so the first item takes focus on the first arrow
  await expect(page.getByRole('option', { name: 'phase → build' })).toBeFocused()
  await page.keyboard.press('Enter')
  await expect(page.getByText('No finished features yet.')).toBeVisible()
  expect((await feature(qa, 'F-2')).phase).toBe('build')
})

