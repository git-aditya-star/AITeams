test('@mention popover inserts a mention by keyboard and by mouse', async ({ page, qa }) => {
  await qa.open('/p/demo?c=general')
  const box = page.getByPlaceholder('Message # general')
  await box.fill('hi @fr')
  await expect(page.getByRole('option', { name: /@frontend/ })).toBeVisible()
  await page.keyboard.press('Enter')
  await expect(box).toHaveValue('hi @frontend ')
  await expect(page.getByRole('option')).toHaveCount(0)
  await box.pressSequentially('@l')
  await page.getByRole('option', { name: /@lead/ }).click()
  await expect(box).toHaveValue('hi @frontend @lead ')
  await expect(box).toBeFocused()
  await box.pressSequentially('@m')
  await expect(page.getByRole('option', { name: /@manager/ })).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(page.getByRole('option')).toHaveCount(0)
  await expect(box).toHaveValue('hi @frontend @lead @m')
})
